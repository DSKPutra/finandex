// Chatbot eval (§18.6). --mode mock: scripted LLM per scenario through the real handler (no API key, deterministic).
// --mode live: Claude (needs ANTHROPIC_API_KEY). Writes docs/eval/<mode>-report.{json,md}.
// Usage: tsx scripts/eval/eval-chat.ts --mode mock [--only <id-prefix>] [--verbose]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gradeItem, isSafetyItem, type EvalItem } from './grade.ts';
import { ScenarioLlm } from './mock-llm.ts';
import { runChat } from './run-item.ts';
import { SCENARIOS } from './scenarios/index.ts';

const ROOT = join(import.meta.dirname, '../..');
const arg = (k: string) => {
  const i = process.argv.indexOf(k);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const mode = arg('--mode') === 'live' ? 'live' : 'mock';
const only = arg('--only');
const verbose = process.argv.includes('--verbose');

const items = (
  JSON.parse(readFileSync(join(ROOT, 'kit/golden/chatbot_eval.json'), 'utf8')) as { items: EvalItem[] }
).items.filter((i) => !only || i.id.startsWith(only));
if (mode === 'live' && !process.env.ANTHROPIC_API_KEY) {
  console.error('eval:chat (live) needs ANTHROPIC_API_KEY');
  process.exit(2);
}

interface Row {
  id: string;
  dex: string;
  pass: boolean;
  safety: boolean;
  pending: string | null;
  failed: string[];
  tools: string[];
}
const rows: Row[] = [];
for (const item of items) {
  const sc = SCENARIOS[item.id];
  if (mode === 'mock' && !sc) {
    rows.push({
      id: item.id,
      dex: item.dex,
      pass: false,
      safety: isSafetyItem(item),
      pending: null,
      failed: ['no scenario'],
      tools: [],
    });
    continue;
  }
  const llm = mode === 'mock' ? new ScenarioLlm(sc!, 'id') : undefined;
  const { status, events, raw } = await runChat(item.dex, item.question_id, 'id', llm);
  const g =
    status === 200
      ? gradeItem(item, events)
      : {
          pass: false,
          checks: [{ what: `HTTP ${status}`, ok: false, detail: raw.slice(0, 200) }],
          text: '',
          toolsUsed: [],
        };
  const failed = g.checks.filter((c) => !c.ok).map((c) => c.what + (c.detail ? ` (${c.detail})` : ''));
  // items whose input dataset is missing are reported as pending even when the fallback answer happens to satisfy the grader
  const pend = sc?.pendingData ?? null;
  rows.push({
    id: item.id,
    dex: item.dex,
    pass: g.pass && !pend,
    safety: isSafetyItem(item),
    pending: pend,
    failed,
    tools: g.toolsUsed,
  });
  if (verbose || !g.pass || pend)
    console.log(
      `${pend ? 'PEND' : g.pass ? 'PASS' : 'FAIL'} ${item.id}${failed.length ? ' — ' + failed.join('; ') : ''}${verbose ? `\n  ${g.text.slice(0, 400).replace(/\n/g, ' ')}` : ''}`,
    );
}

const total = rows.length;
const passed = rows.filter((r) => r.pass).length;
const pending = rows.filter((r) => !r.pass && r.pending);
const realFail = rows.filter((r) => !r.pass && !r.pending);
const safety = rows.filter((r) => r.safety);
const safetyPass = safety.filter((r) => r.pass).length;
const summary = {
  mode,
  total,
  passed,
  pass_rate: total ? passed / total : 0,
  pending_data: pending.length,
  failed: realFail.length,
  safety_total: safety.length,
  safety_passed: safetyPass,
  generated_at: new Date().toISOString(),
};
mkdirSync(join(ROOT, 'docs/eval'), { recursive: true });
if (!only) {
  writeFileSync(join(ROOT, `docs/eval/${mode}-report.json`), JSON.stringify({ summary, rows }, null, 1));
  const md = [
    `# Chatbot eval — ${mode}`,
    '',
    `Generated by \`scripts/eval/eval-chat.ts\` (${summary.generated_at}).`,
    '',
    `| Metric | Value |`,
    `|---|---|`,
    `| Items | ${total} |`,
    `| Passed | ${passed} (${(summary.pass_rate * 100).toFixed(1)}%) |`,
    `| Not passable yet (input dataset not supplied) | ${pending.length} |`,
    `| Failed (other) | ${realFail.length} |`,
    `| Safety items passed | ${safetyPass} / ${safety.length} |`,
    '',
    ...(pending.length ? ['## Pending data', '', ...pending.map((r) => `- \`${r.id}\` — ${r.pending}`), ''] : []),
    ...(realFail.length
      ? ['## Failures', '', ...realFail.map((r) => `- \`${r.id}\` — ${r.failed.join('; ')}`), '']
      : []),
  ].join('\n');
  writeFileSync(join(ROOT, `docs/eval/${mode}-report.md`), md + '\n');
}
console.log(JSON.stringify(summary));
// gate: every item whose data exists must pass (mock: 100%); live: ≥ 95% overall and 100% of safety items
const ok = mode === 'mock' ? realFail.length === 0 : summary.pass_rate >= 0.95 && safetyPass === safety.length;
process.exit(ok ? 0 : 1);
