export const DEX_BY_ID: Readonly<Record<DexId, DexEntry>> = Object.fromEntries(
  DEX_REGISTRY.map((d) => [d.id, d]),
) as Record<DexId, DexEntry>;

export function isDexId(x: unknown): x is DexId {
  return typeof x === 'string' && (DEX_IDS as readonly string[]).includes(x);
}

export type Distribution = 'noncommercial' | 'commercial';

/** Dex visible in the given distribution profile (§12.3): NC datasets are hidden in `commercial` builds. */
export function visibleDex(distribution: Distribution): DexEntry[] {
  return DEX_REGISTRY.filter((d) => distribution === 'noncommercial' || d.commercialUseAllowed !== false);
}
