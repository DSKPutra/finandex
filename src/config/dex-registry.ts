export type DexLicense = 'unknown' | 'CC BY 4.0' | 'CC BY-NC 4.0' | 'mixed';
export type DexStatus = 'live' | 'partial' | 'pending-data';
export interface Label {
  id: string;
  en: string;
}
export interface DexTab {
  id: string;
  label: Label;
}

export interface DexEntry {
  id: DexId;
  name: string;
  group: DexGroupId;
  order: number;
  tagline: Label;
  /** file name (without extension) in kit/brand/icons → served from /icons/<icon>.svg */
  icon: string;
  /** file numbers of §3.1 */
  inputs: number[];
  /** Documented as-of label; the UI shows public/data/manifest.json `dex.<id>.as_of` and only falls back to this. */
  asOf: string;
  license: DexLicense;
  commercialUseAllowed: boolean | 'unknown';
  /** tab[0] = 'chat', tab[last] = 'data' */
  tabs: DexTab[];
  status: DexStatus;
  /** Why the status is not 'live' (shown in UI). */
  statusNote?: Label;
  /** Sample share (e.g. 0.16) when the dataset is a sample. */
  sample?: number;
  /** Dataset is synthetic (CostLivingDex). */
  synthetic?: boolean;
  indonesia: boolean;
  /** Folder name under public/data/{core,heavy}/ */
  dataKey: string;
  /** One-line scope sentence used in the system prompt ({DEX_SCOPE}). */
  scope: Label;
  keywords: string[];
}

